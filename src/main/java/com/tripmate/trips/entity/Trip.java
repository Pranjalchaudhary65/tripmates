package com.tripmate.trips.entity;

import com.tripmate.vibe.entity.BudgetBand;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.Objects;
import java.util.UUID;

/**
 * A trip a host offers to travel companions (DESIGN.md §3 trips).
 *
 * <p>{@code destination_point}, the PostGIS geography, is generated by the
 * database from the two coordinates and is not mapped: radius queries read
 * it in SQL, and nothing in Java needs a spatial type.
 *
 * <p>Slots move only through {@link #claimSlot}, and every change bumps
 * {@code version}. Two claims that read the same row both try to write
 * {@code WHERE version = ?}; the second matches no row and fails its commit,
 * so a trip can never be filled twice over by requests that each saw a free
 * slot.
 */
@Entity
@Table(name = "trips")
public class Trip {

    public static final int MAX_SLOTS = 20;

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "host_user_id", nullable = false, updatable = false)
    private UUID hostUserId;

    @Column(nullable = false, length = 140)
    private String title;

    @Column(nullable = false)
    private String description;

    @Column(name = "destination_name", nullable = false)
    private String destinationName;

    @Column(name = "destination_latitude", nullable = false)
    private double destinationLatitude;

    @Column(name = "destination_longitude", nullable = false)
    private double destinationLongitude;

    @Column(name = "destination_radius_km", nullable = false, precision = 6, scale = 2)
    private BigDecimal destinationRadiusKm;

    @Column(name = "start_date", nullable = false)
    private LocalDate startDate;

    @Column(name = "end_date", nullable = false)
    private LocalDate endDate;

    @Column(name = "total_slots", nullable = false)
    private short totalSlots;

    @Column(name = "filled_slots", nullable = false)
    private short filledSlots;

    @Enumerated(EnumType.STRING)
    @Column(name = "budget_band", nullable = false, length = 20)
    private BudgetBand budgetBand;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private TripStatus status;

    @Version
    @Column(nullable = false)
    private long version;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Trip() {
    }

    public static Trip open(UUID hostUserId, TripDetails details, Instant now) {
        Objects.requireNonNull(hostUserId, "hostUserId");
        Objects.requireNonNull(details, "details");
        Trip trip = new Trip();
        trip.hostUserId = hostUserId;
        trip.title = details.title();
        trip.description = details.description();
        trip.destinationName = details.destinationName();
        trip.destinationLatitude = details.latitude();
        trip.destinationLongitude = details.longitude();
        trip.destinationRadiusKm = details.radiusKm();
        trip.startDate = details.startDate();
        trip.endDate = details.endDate();
        trip.totalSlots = (short) details.totalSlots();
        trip.budgetBand = details.budgetBand();
        trip.status = TripStatus.OPEN;
        trip.createdAt = now;
        trip.updatedAt = now;
        return trip;
    }

    public boolean isHostedBy(UUID userId) {
        return hostUserId.equals(userId);
    }

    /** Started trips take no more companions; "today" is the caller's to pass, in the platform's zone. */
    public boolean hasStarted(LocalDate today) {
        return startDate.isBefore(today);
    }

    /**
     * Gives one slot to an accepted companion. The caller checks that the
     * trip is OPEN and has not started; this refuses outright if it is not,
     * so no caller can overfill a trip by skipping the check.
     */
    public void claimSlot(Instant now) {
        if (status != TripStatus.OPEN || filledSlots >= totalSlots) {
            throw new IllegalStateException("Trip has no open slot");
        }
        filledSlots++;
        if (filledSlots == totalSlots) {
            status = TripStatus.FULL;
        }
        updatedAt = now;
    }

    public UUID getId() {
        return id;
    }

    public UUID getHostUserId() {
        return hostUserId;
    }

    public String getTitle() {
        return title;
    }

    public String getDescription() {
        return description;
    }

    public String getDestinationName() {
        return destinationName;
    }

    public double getDestinationLatitude() {
        return destinationLatitude;
    }

    public double getDestinationLongitude() {
        return destinationLongitude;
    }

    public BigDecimal getDestinationRadiusKm() {
        return destinationRadiusKm;
    }

    public LocalDate getStartDate() {
        return startDate;
    }

    public LocalDate getEndDate() {
        return endDate;
    }

    public short getTotalSlots() {
        return totalSlots;
    }

    public short getFilledSlots() {
        return filledSlots;
    }

    public BudgetBand getBudgetBand() {
        return budgetBand;
    }

    public TripStatus getStatus() {
        return status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
